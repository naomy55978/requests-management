using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using RequestsManagement.DAL.Entities;

namespace RequestsManagement.DAL.Configurations;

internal class RequestConfiguration : IEntityTypeConfiguration<Request>
{
    public void Configure(EntityTypeBuilder<Request> builder)
    {
        // Check constraints keep invalid enum values out of the table even if written outside the application
        builder.ToTable("Requests", t =>
        {
            t.HasCheckConstraint("CK_Requests_Status", "[Status] BETWEEN 1 AND 4");
            t.HasCheckConstraint("CK_Requests_Priority", "[Priority] BETWEEN 1 AND 3");
        });

        builder.HasKey(r => r.Id);
        builder.Property(r => r.Id).UseIdentityColumn();

        builder.Property(r => r.Title).HasMaxLength(200).IsRequired();
        builder.Property(r => r.OrganizationName).HasMaxLength(150).IsRequired();
        builder.Property(r => r.Status).HasColumnType("tinyint");
        builder.Property(r => r.Priority).HasColumnType("tinyint");
        builder.Property(r => r.AssignedTo).HasMaxLength(100);
        builder.Property(r => r.CreatedAt).HasColumnType("datetime2");
        builder.Property(r => r.UpdatedAt).HasColumnType("datetime2");

        // rowversion: generated by SQL Server on every insert/update and used as the concurrency token
        builder.Property(r => r.RowVersion).IsRowVersion();
    }
}
